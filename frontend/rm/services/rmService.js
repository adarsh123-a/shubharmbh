const API_BASE = '/api';

const getAuthHeaders = () => {
  const headers = { 'Content-Type': 'application/json' };
  const token = typeof window !== 'undefined' ? localStorage.getItem('auth_token') : null;
  if (token) {
    headers['Authorization'] = `Bearer ${token}`;
  }
  return headers;
};

export const rmService = {
  // RM Operational Dashboard KPIs
  async getDashboard() {
    try {
      const res = await fetch(`${API_BASE}/rm/dashboard`, {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      return data.data;
    } catch (err) {
      console.warn('rmService.getDashboard fallback:', err.message);
      return null;
    }
  },

  // Customer Leads generated by Agents
  async getLeads() {
    try {
      const res = await fetch(`${API_BASE}/rm/customers`, {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      return Array.isArray(data.data) ? data.data : [];
    } catch (err) {
      console.warn('rmService.getLeads fallback:', err.message);
      return null;
    }
  },

  // Update lead status (e.g. contacted, visit_scheduled, booked, lost) and notes after contacting
  async updateLead(id, payload) {
    const res = await fetch(`${API_BASE}/rm/customers/${id}`, {
      method: 'PATCH',
      headers: getAuthHeaders(),
      credentials: 'include',
      body: JSON.stringify(payload),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.message || 'Failed to update lead');
    return data.data;
  },

  // Managed Agents under this RM
  async getAgents() {
    try {
      const res = await fetch(`${API_BASE}/rm/agents`, {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      return Array.isArray(data.data) ? data.data : [];
    } catch (err) {
      console.warn('rmService.getAgents fallback:', err.message);
      return null;
    }
  },

  // Onboard new Agent under this RM
  async createAgent(agentData) {
    const res = await fetch(`${API_BASE}/rm/agents`, {
      method: 'POST',
      headers: getAuthHeaders(),
      credentials: 'include',
      body: JSON.stringify(agentData),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.message || 'Failed to create agent');
    return data.data;
  },

  // Site visits & cab coordination
  async getVisits() {
    try {
      const res = await fetch(`${API_BASE}/rm/visits`, {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      return Array.isArray(data.data) ? data.data : [];
    } catch (err) {
      console.warn('rmService.getVisits fallback:', err.message);
      return null;
    }
  },

  // Update visit status / assign driver
  async updateVisitStatus(id, payload) {
    const res = await fetch(`${API_BASE}/rm/visits/${id}`, {
      method: 'PATCH',
      headers: getAuthHeaders(),
      credentials: 'include',
      body: JSON.stringify(payload),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.message || 'Failed to update visit status');
    return data.data;
  },

  // Plot bookings submitted by agents
  async getBookings() {
    try {
      const res = await fetch(`${API_BASE}/rm/bookings`, {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      return Array.isArray(data.data) ? data.data : [];
    } catch (err) {
      console.warn('rmService.getBookings fallback:', err.message);
      return null;
    }
  },

  // Forward booking to Admin or Reject
  async reviewBooking(id, payload) {
    const res = await fetch(`${API_BASE}/rm/bookings/${id}/review`, {
      method: 'PATCH',
      headers: getAuthHeaders(),
      credentials: 'include',
      body: JSON.stringify(payload),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.message || 'Failed to review booking');
    return data.data;
  },
};
